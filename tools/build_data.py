#!/usr/bin/env python3
"""Rebuild the game reference data embedded in index.html from the MeowDB pages
that .github/workflows/fetch-icons.yml saves into assets/meowdb/.

  EXP_REQ[L]  = EXP the bar fills at level L (to reach L+1) — MeowDB row L, 'EXP to next'
  ALL_MAPS    = [mapId, name, street] for every map MeowDB lists

Run from the repo root:  python3 tools/build_data.py
"""
import html, json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'assets' / 'meowdb'

def text_of(page):
    s = (src / page).read_text(encoding='utf-8')
    s = re.sub(r'<script.*?</script>', '', s, flags=re.S)
    return html.unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', s)))

# ---- EXP table: rows "level  exp-to-reach-this-level  cumulative" ----
t = text_of('exp-table.html')
rows = {}
for m in re.finditer(r'(?<![\d,])(\d{1,3}) ([\d,]+) ([\d,]+)(?= )', t):
    L, a, c = int(m.group(1)), int(m.group(2).replace(',', '')), int(m.group(3).replace(',', ''))
    if 1 <= L <= 100 and L not in rows:
        rows[L] = (a, c)
for L in range(3, max(rows) + 1):          # the table must be self-consistent
    assert rows[L - 1][1] + rows[L][0] == rows[L][1], f'EXP table mismatch at {L}'
# MeowDB's column is "EXP to next": row L = the EXP the bar fills at level L (checked on the game HUD:
# Lv.63 shows 40,652 = 2.86% of 1,420,016, which is row 63)
exp_req = [0] * (max(rows) + 1)
for L in range(1, max(rows) + 1):
    exp_req[L] = rows[L][0]

# ---- maps: links under street headings ----
s = (src / 'maps-all.html').read_text(encoding='utf-8')
maps, street, seen = [], '', set()
for m in re.finditer(r'<h[234][^>]*>(.*?)</h[234]>|href="/msclassic/maps/(\d{9})"[^>]*>(.*?)</a>', s, flags=re.S):
    if m.group(1) is not None:
        h = html.unescape(re.sub(r'<[^>]+>', '', m.group(1))).strip()
        street = re.sub(r'\s*\(\d+\)$', '', h)
        continue
    mid = m.group(2)
    name = html.unescape(re.sub(r'<[^>]+>', ' ', m.group(3)))
    name = re.sub(r'\s*\(town\)\s*', ' ', name)
    name = re.sub(r'\s+', ' ', name).strip()
    if mid in seen or not name:
        continue
    seen.add(mid)
    maps.append([mid, name, street])

h = root / 'index.html'
page = h.read_text(encoding='utf-8')
block = ('/* @data:begin — generated by tools/build_data.py from MeowDB, do not edit by hand */\n'
         f'const EXP_REQ={json.dumps(exp_req, separators=(",", ":"))};\n'
         f'const ALL_MAPS={json.dumps(maps, ensure_ascii=False, separators=(",", ":"))};\n'
         '/* @data:end */')
if '/* @data:begin' in page:
    page = re.sub(r'/\* @data:begin.*?/\* @data:end \*/', lambda _: block, page, flags=re.S)
else:
    page = page.replace('const BUILTIN_MAPS=[', block + '\nconst BUILTIN_MAPS=[', 1)
h.write_text(page, encoding='utf-8')
print(f'EXP_REQ levels 1-{len(exp_req)-1}, maps {len(maps)}')
